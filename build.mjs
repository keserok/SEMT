import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// 1. Ensure assets directory exists at root and sync all assets from public/assets
const publicAssetsDir = path.join(__dirname, 'public/assets');
const rootAssetsDir = path.join(__dirname, 'assets');
if (fs.existsSync(publicAssetsDir)) {
  fs.cpSync(publicAssetsDir, rootAssetsDir, { recursive: true });
  console.log('✨ Synced all media assets to root /assets directory!');
}

const dataContent = fs.readFileSync(path.join(__dirname, 'src/data/karakoyData.js'), 'utf-8');
const audioContent = fs.readFileSync(path.join(__dirname, 'src/engine/audioHaptics.js'), 'utf-8');
const mapContent = fs.readFileSync(path.join(__dirname, 'src/engine/mapCanvas.js'), 'utf-8');
const appContent = fs.readFileSync(path.join(__dirname, 'src/app.js'), 'utf-8');
const webPortalContent = fs.readFileSync(path.join(__dirname, 'src/webPortal.js'), 'utf-8');

// Strip exports and imports
const cleanData = dataContent.replace(/export\s+const\s+/g, 'const ');
const cleanAudio = audioContent
  .replace(/export\s+const\s+audioEngine\s*=\s*new\s+AudioHapticsEngine\(\);/g, 'const audioEngine = new AudioHapticsEngine();')
  .replace(/export\s+class\s+AudioHapticsEngine/g, 'class AudioHapticsEngine');

const cleanMap = mapContent.replace(/export\s+class\s+SemtMapEngine/g, 'class SemtMapEngine');

const cleanApp = appContent
  .replace(/import\s*\{[\s\S]*?\}\s*from\s*['"].*?['"];/g, '')
  .replace(/import\s+.*?\s+from\s*['"].*?['"];/g, '');

const cleanWebPortal = webPortalContent
  .replace(/export\s+class\s+/g, 'class ')
  .replace(/export\s+const\s+/g, 'const ')
  .replace(/export\s+default\s+/g, '');

const bundle = `// SEMT Spatial Studio & Capitolium Web Portal Unified Bundle
// Auto-generated by build.mjs — Awwwards SOTD Web Portal + Mobile Field PWA

${cleanData}

${cleanAudio}

${cleanMap}

${cleanApp}

${cleanWebPortal}

window.addEventListener('DOMContentLoaded', () => {
  // 1. Initialize Capitolium Web Portal immediately (Primary viewport & LCP critical path)
  const portal = new SemtCapitoliumPortal();
  portal.init();
  window.semtPortal = portal;

  // 2. Instantiate SemtApp
  const app = new SemtApp();
  window.semtApp = app;

  // 3. Lazy initialize SemtApp field engine during browser idle time to optimize TBT and INP
  let appInitialized = false;
  const lazyInitApp = () => {
    if (appInitialized) return;
    appInitialized = true;
    app.init();
  };

  window.initSemtAppLazy = lazyInitApp;

  if ('requestIdleCallback' in window) {
    window.requestIdleCallback(lazyInitApp, { timeout: 2000 });
  } else {
    setTimeout(lazyInitApp, 800);
  }
});
`;

fs.writeFileSync(path.join(__dirname, 'src/bundle.js'), bundle, 'utf-8');
console.log('✨ src/bundle.js successfully built! (' + bundle.length + ' bytes)');

// Also update index.html's inlined SemtMapEngine, SemtApp & SemtCapitoliumPortal
const indexPath = path.join(__dirname, 'index.html');
let indexHtml = fs.readFileSync(indexPath, 'utf-8');

// Read capitoliumWeb.css and copy to root & public/styles for static serving
const cssPath = path.join(__dirname, 'src/styles/capitoliumWeb.css');
const cssContent = fs.readFileSync(cssPath, 'utf-8');

fs.writeFileSync(path.join(__dirname, 'capitoliumWeb.css'), cssContent, 'utf-8');
const publicStylesDir = path.join(__dirname, 'public/styles');
if (!fs.existsSync(publicStylesDir)) {
  fs.mkdirSync(publicStylesDir, { recursive: true });
}
fs.writeFileSync(path.join(publicStylesDir, 'capitoliumWeb.css'), cssContent, 'utf-8');

// Inline CSS into index.html to guarantee 100% fail-proof rendering with 0 network roundtrips
const cssMarkerStart = '/* CAPITOLIUM_PORTAL_CSS_START */';
const cssMarkerEnd = '/* CAPITOLIUM_PORTAL_CSS_END */';
const cssStartIdx = indexHtml.indexOf(cssMarkerStart);
const cssEndIdx = indexHtml.indexOf(cssMarkerEnd);

if (cssStartIdx !== -1 && cssEndIdx !== -1) {
  indexHtml = indexHtml.substring(0, cssStartIdx + cssMarkerStart.length) + '\n' + cssContent + '\n' + indexHtml.substring(cssEndIdx);
  console.log('✨ index.html inlined CSS styles successfully synchronized!');
}

const marker = '// SEMT v2.0 — Luxury Architectural 3D Map Engine';
const markerIdx = indexHtml.indexOf(marker);

if (markerIdx !== -1) {
  const endScriptIdx = indexHtml.indexOf('</script>', markerIdx);
  if (endScriptIdx !== -1) {
    const newEngineAndApp = `${marker}

${cleanMap}

${cleanApp}

${cleanWebPortal}

window.addEventListener('DOMContentLoaded', () => {
  // 1. Initialize Capitolium Web Portal immediately (Primary viewport & LCP critical path)
  const portal = new SemtCapitoliumPortal();
  portal.init();
  window.semtPortal = portal;

  // 2. Instantiate SemtApp
  const app = new SemtApp();
  window.semtApp = app;

  // 3. Lazy initialize SemtApp field engine during browser idle time to optimize TBT and INP
  let appInitialized = false;
  const lazyInitApp = () => {
    if (appInitialized) return;
    appInitialized = true;
    app.init();
  };

  window.initSemtAppLazy = lazyInitApp;

  if ('requestIdleCallback' in window) {
    window.requestIdleCallback(lazyInitApp, { timeout: 2000 });
  } else {
    setTimeout(lazyInitApp, 800);
  }
});
`;
    indexHtml = indexHtml.substring(0, markerIdx) + newEngineAndApp + indexHtml.substring(endScriptIdx);
  }
}

// Global cleanup on index.html: normalize all image URLs to /assets/
indexHtml = indexHtml.replaceAll('https://semt-istanbul.com/public/assets/', 'https://semt-istanbul.com/assets/');
indexHtml = indexHtml.replaceAll('"public/assets/', '"/assets/');
indexHtml = indexHtml.replaceAll('\'public/assets/', '\'/assets/');

// Remove debug/technical SEO copy from user-facing markup
indexHtml = indexHtml.replaceAll(
  'PROGRAMATİK SEO DİZİNİ · GOOGLE İNDEKSİNE HAZIR 2.400 MİKRO ROTA',
  'SEMT KÜRASYON ARŞİVİ · İSTANBUL MİMARİ VE KÜLTÜR ROTALARI'
);
indexHtml = indexHtml.replaceAll(
  'SCHEMA.ORG TOURISTTRIP & FAQ YAPILANDIRMASI AKTİF',
  '6 ÖZEL EDİTÖRYAL PARKUR · SESLİ REHBERLİ'
);
indexHtml = indexHtml.replaceAll(
  '<span class="cap-menu-item__chap">pSEO KEŞİF KÜTÜPHANESİ</span>',
  '<span class="cap-menu-item__chap">05 · KÜRASYON ARŞİVİ</span>'
);
indexHtml = indexHtml.replaceAll(
  '<span class="cap-menu-item__title">Otomatik Rota & pSEO Arşivi</span>',
  '<span class="cap-menu-item__title">İstanbul Niş Rota Kütüphanesi</span>'
);
indexHtml = indexHtml.replaceAll(
  '<span class="cap-menu-item__sub">Google İndeksli 2.400 Mikro Rota ve Detaylı Adımlar</span>',
  '<span class="cap-menu-item__sub">Fotoğraf, Sessiz Çalışma, Tarih ve Boğaz Parkurları</span>'
);

fs.writeFileSync(indexPath, indexHtml, 'utf-8');
console.log('✨ index.html fully synchronized and sanitized!');
